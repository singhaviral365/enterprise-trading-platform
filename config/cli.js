const SECRET_NAME = /PASSWORD|SECRET|API_KEY|PRIVATE_KEY|^E2E_(READONLY_)?USERNAME$/;

function envValue(config, source) {
  return typeof source === 'function' ? text(source(config)) : text(get(config, source));
}

function envQuote(value) {
  if (value === '') return '';
  if (value.includes('\n')) return `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n')}"`;
  if (/^[A-Za-z0-9_@%+=:,./-]*$/.test(value)) return value;
  return value.includes("'") ? `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"` : `'${value}'`;
}

function envFileText(config, withSecrets, headerLines) {
  const out = [...headerLines, ''];
  const seen = new Set();
  for (const [section, entries] of ENV_SPEC) {
    out.push(`# ---- ${section}`);
    for (const [name, source] of entries) {
      if (seen.has(name)) {
        continue; // a name shared by two parts is written once, under the first
      }
      seen.add(name);
      const value = !withSecrets && SECRET_NAME.test(name) ? '' : envValue(config, source);
      out.push(`${name}=${envQuote(value)}`);
    }
    out.push('');
  }
  return out.join('\n');
}

function writeEnvFiles() {
  const { config } = load();
  const example = yamlParser().load(fs.readFileSync(EXAMPLE, 'utf8')) || {};
  const real = envFileText(config, true, [
    '# Generated by `node config/cli.js env-file` from config/application.yml. Git-ignored: it holds secrets. Edit application.yml, not this file.',
    '# docker compose reads it from here; the services also read application.yml, and a variable set here overrides its key.',
  ]);
  const template = envFileText(example, false, [
    '# Every environment variable the platform uses, by the part that reads it. Copy it to .env and fill in the blanks (or let',
    '# `node config/cli.js env-file` write .env from config/application.yml). Generated from config/application.example.yml, so it stays in step.',
    '# Blank = a secret or an account you must supply: passwords, API keys, the JWT secret, the encryption key, the SMTP account.',
  ]);
  fs.writeFileSync(path.join(ROOT, '.env'), real + '\n');
  fs.writeFileSync(path.join(ROOT, '.env.example'), template + '\n');
  return ENV_SPEC.reduce((n, [, e]) => n + e.length, 0);
}

function flatten(node, prefix, out) {
  for (const [key, value] of Object.entries(node)) {
    const name = prefix ? `${prefix}.${key}` : key;
    if (value !== null && typeof value === 'object' && !Array.isArray(value)) {
      flatten(value, name, out);
    } else {
      out[name] = Array.isArray(value) ? value.join(',') : text(value);
    }
  }
  return out;
}

function quote(value) {
  return /^[A-Za-z0-9_@%+=:,./-]*$/.test(value) ? value : `'${value.replace(/'/g, `'\\''`)}'`;
}

// ------------------------------------------------------------------------------------------------------------- check

function check(config, usingExample) {
  const problems = [];
  const g = (k) => text(get(config, k));
  if (usingExample) {
    problems.push('config/application.yml does not exist: copy config/application.example.yml to config/application.yml and fill it in');
  }
  if (g('jwt.secret').length < 32) {
    problems.push('jwt.secret must be at least 32 characters');
  }
  for (const db of ['trading', 'auth']) {
    if (g(`database.${db}.password`) === '') {
      problems.push(`database.${db}.password is empty`);
    }
  }
  for (const [name, mode] of [
    ['auth.email', g('auth.email.mode')],
    ['order.email', g('order.email.mode')],
  ]) {
    if (!['off', 'dev', 'prod'].includes(mode)) {
      problems.push(`${name}.mode must be off, dev or prod`);
    }
    if (mode === 'prod') {
      const smtp = name === 'auth.email' ? ['host', 'user', 'password'] : ['host', 'username', 'password'];
      for (const key of smtp) {
        if (g(`${name}.smtp.${key}`) === '') {
          problems.push(`${name}.smtp.${key} is required when ${name}.mode is prod`);
        }
      }
      if (g(`${name}.from`) === '' || g(`${name}.from-domains`) === '') {
        problems.push(`${name}.from and ${name}.from-domains are required when ${name}.mode is prod`);
      }
    }
  }
  const enc = g('encryption.mode');
  if (!['off', 'optional', 'required'].includes(enc)) {
    problems.push('encryption.mode must be off, optional or required');
  } else if (enc !== 'off' && (g('encryption.private-key-pem') === '' || g('encryption.kid') === '')) {
    problems.push('encryption.kid and encryption.private-key-pem are required when encryption.mode is not off (node config/cli.js enc-key)');
  }
  return problems;
}

// ------------------------------------------------------------------------------------------------------------ main

function main() {
  const [command, arg] = process.argv.slice(2);
  if (command === 'enc-key') {
    const { generateKeyPairSync } = require('crypto');
    const { privateKey } = generateKeyPairSync('rsa', { modulusLength: 3072 });
    const pem = privateKey.export({ type: 'pkcs8', format: 'pem' }).toString().trim().replace(/\n/g, '\\n');
    console.log(`  kid: auth-${new Date().toISOString().slice(0, 7)}`);
    console.log(`  private-key-pem: "${pem}"`);
    console.error('\nPaste these two lines under `encryption:` in config/application.yml. Keep the private key out of git.');
    return;
  }
  const { config, usingExample } = load();
  switch (command) {
    case 'get': {
      const m = /^services\.([a-z]+)\.url$/.exec(arg || '');
      const value = m ? service(config, m[1]).url : get(config, arg || '');
      if (value === undefined) {
        console.error(`config: no key "${arg}"`);
        process.exit(1);
      }
      console.log(typeof value === 'object' ? JSON.stringify(value) : String(value));
      break;
    }
    case 'frontend':
      frontend(config);
      break;
    case 'serve':
      serve(config);
      break;
    case 'contracts':
      contracts(config);
      break;
    case 'env-file':
    case 'compose-env': {
      const n = writeEnvFiles();
      console.log(`config: wrote .env and .env.example (${n} variables)`);
      break;
    }
    case 'env': {
      const flat = flatten(config, '', {});
      for (const [k, v] of Object.entries(flat)) {
        console.log(`${k.toUpperCase().replace(/[.-]/g, '_')}=${quote(v)}`);
      }
      break;
    }
    case 'check': {
      const problems = check(config, usingExample);
      if (problems.length) {
        console.error('config: ' + problems.join('\nconfig: '));
        process.exit(1);
      }
      console.log('config: ok');
      break;
    }
    default:
      console.error('usage: node config/cli.js get|frontend|serve|contracts|env-file|env|check|enc-key');
      process.exit(2);
  }
}

main();
