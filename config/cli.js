#!/usr/bin/env node
/*
 * The command line of the central configuration (config/application.yml, falling back to config/application.example.yml).
 *
 *   node config/cli.js get <dotted.key>      print one value (a service also has a derived `.url`, for example services.order.url)
 *   node config/cli.js frontend              write frontend/src/app/config/platform.config.ts and frontend/proxy.conf.json
 *   node config/cli.js serve                 the above, then `ng serve` on services.frontend.port with the proxy
 *   node config/cli.js contracts             write the `servers:` URLs of every contract in contracts/*.yaml
 *   node config/cli.js compose-env [file]    write the variables docker compose reads (default services/.env)
 *   node config/cli.js env                   print every key as KEY=VALUE shell lines (for scripts.sh and other shells)
 *   node config/cli.js check                 explain what is missing or unsafe, exit 1 on a problem
 *   node config/cli.js enc-key               print a new payload-encryption key as the two lines to paste into application.yml
 */
'use strict';

const fs = require('fs');
const path = require('path');
const { spawn } = require('child_process');

const ROOT = path.resolve(__dirname, '..');
const REAL = process.env.CONFIG_FILE ? path.resolve(process.env.CONFIG_FILE) : path.join(__dirname, 'application.yml');
const EXAMPLE = path.join(__dirname, 'application.example.yml');

function yamlParser() {
  try {
    return require('js-yaml');
  } catch {
    console.error('config: js-yaml is missing. Run `npm install` in the config folder.');
    process.exit(2);
  }
}

function merge(base, over) {
  if (over === null || typeof over !== 'object' || Array.isArray(over)) {
    return over === undefined ? base : over;
  }
  const out = { ...(base && typeof base === 'object' && !Array.isArray(base) ? base : {}) };
  for (const [key, value] of Object.entries(over)) {
    out[key] = merge(out[key], value);
  }
  return out;
}

function load() {
  const yaml = yamlParser();
  const example = yaml.load(fs.readFileSync(EXAMPLE, 'utf8')) || {};
  const real = fs.existsSync(REAL) ? yaml.load(fs.readFileSync(REAL, 'utf8')) || {} : null;
  return { config: real ? merge(example, real) : example, usingExample: real === null };
}

function get(config, dotted) {
  return dotted.split('.').reduce((node, key) => (node === undefined || node === null ? undefined : node[key]), config);
}

function service(config, name) {
  const s = config.services[name];
  return { ...s, url: `http://${s.host}:${s.port}` };
}

function text(value) {
  return value === undefined || value === null ? '' : String(value);
}

// ---------------------------------------------------------------------------------------------------------- frontend

function writeIfChanged(file, content) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== content) {
    fs.writeFileSync(file, content);
    return true;
  }
  return false;
}

function frontend(config) {
  const urls = {
    frontendUrl: service(config, 'frontend').url,
    authUrl: service(config, 'auth').url,
    orderUrl: service(config, 'order').url,
    executorUrl: service(config, 'executor').url,
    mailhogWebUrl: `http://${config.services.mailhog.host}:${config.services.mailhog['web-port']}`,
  };
  const ts =
    '// Generated by config/cli.js from config/application.yml. Do not edit; it is git-ignored and rewritten by npm start, build and test.\n' +
    'export const PLATFORM = {\n' +
    Object.entries(urls)
      .map(([k, v]) => `  ${k}: '${v}',`)
      .join('\n') +
    '\n} as const;\n';
  writeIfChanged(path.join(ROOT, 'frontend/src/app/config/platform.config.ts'), ts);

  // ng serve proxies same-origin calls to the services that have no CORS: market data to the executor, the rest of /api to the order-service.
  const proxy = {
    '/api/v1/market': { target: urls.executorUrl, secure: false, changeOrigin: true },
    '/api': { target: urls.orderUrl, secure: false, changeOrigin: true },
  };
  writeIfChanged(path.join(ROOT, 'frontend/proxy.conf.json'), JSON.stringify(proxy, null, 2) + '\n');

  // The Playwright journeys read these as E2E_* variables (frontend/playwright.config.ts); an E2E_* already in the environment wins.
  const e2e = {
    E2E_BASE_URL: urls.frontendUrl,
    E2E_MAILHOG_URL: urls.mailhogWebUrl,
    E2E_USERNAME: text(get(config, 'e2e.username')),
    E2E_PASSWORD: text(get(config, 'e2e.password')),
    E2E_READONLY_USERNAME: text(get(config, 'e2e.readonly-username')),
    E2E_READONLY_PASSWORD: text(get(config, 'e2e.readonly-password')),
    E2E_SYMBOL: text(get(config, 'e2e.symbol')),
  };
  writeIfChanged(path.join(ROOT, 'frontend/e2e/support/e2e-config.generated.json'), JSON.stringify(e2e, null, 2) + '\n');
}

function serve(config) {
  frontend(config);
  const port = String(service(config, 'frontend').port);
  const child = spawn('npx', ['ng', 'serve', '--port', port, '--proxy-config', 'proxy.conf.json', ...process.argv.slice(3)], {
    cwd: path.join(ROOT, 'frontend'),
    stdio: 'inherit',
    shell: true,
  });
  child.on('exit', (code) => process.exit(code === null ? 1 : code));
}

// --------------------------------------------------------------------------------------------------------- contracts

const AUTH_CONTRACTS = ['auth-api.yaml'];

function contracts(config) {
  const dir = path.join(ROOT, 'contracts');
  for (const file of fs.readdirSync(dir).filter((f) => f.endsWith('.yaml'))) {
    const owner = AUTH_CONTRACTS.includes(file) ? 'auth' : 'order';
    const p = path.join(dir, file);
    const raw = fs.readFileSync(p, 'utf8');
    const crlf = raw.includes('\r\n');
    const lines = raw.replace(/\r\n/g, '\n').split('\n');
    const start = lines.findIndex((l) => l === 'servers:');
    if (start < 0) {
      continue;
    }
    let first = true;
    for (let i = start + 1; i < lines.length && (lines[i].startsWith('  ') || lines[i] === ''); i++) {
      if (/^  - url: /.test(lines[i])) {
        // The first server is the one a developer runs; a later one names the service inside the docker network and is left alone.
        if (first) {
          lines[i] = `  - url: ${service(config, owner).url}`;
          first = false;
        }
      }
    }
    const out = lines.join('\n');
    fs.writeFileSync(p, crlf ? out.replace(/\n/g, '\r\n') : out);
  }
}

// ------------------------------------------------------------------------------------------------------ compose / env

function composeVariables(config) {
  const g = (k) => text(get(config, k));
  return {
    POSTGRES_DB: g('database.trading.name'),
    POSTGRES_USER: g('database.trading.user'),
    POSTGRES_PASSWORD: g('database.trading.password'),
    TRADING_DB_PORT: g('database.trading.port'),
    AUTH_DB_NAME: g('database.auth.name'),
    AUTH_DB_PORT: g('database.auth.port'),
    KAFKA_PORT: g('kafka.external-port'),
    KAFKA_EXTERNAL_HOST: g('kafka.external-host'),
    AUTH_PORT: g('services.auth.port'),
    ORDER_PORT: g('services.order.port'),
    BACKEND_SPRING_PROFILES_ACTIVE: g('order.email.mode') === 'off' ? '' : g('order.email.mode'),
    CORE_JAVA_REPO_URL: g('docker.core-java-repo-url'),
    CORE_JAVA_REF: g('docker.core-java-ref'),
  };
}

function flatten(node, prefix, out) {
  for (const [key, value] of Object.entries(node)) {
    const name = prefix ? `${prefix}.${key}` : key;
    if (value !== null && typeof value === 'object' && !Array.isArray(value)) {
      flatten(value, name, out);
    } else {
      out[name] = Array.isArray(value) ? value.join(',') : text(value);
    }
  }
  return out;
}

function quote(value) {
  return /^[A-Za-z0-9_@%+=:,./-]*$/.test(value) ? value : `'${value.replace(/'/g, `'\\''`)}'`;
}

// ------------------------------------------------------------------------------------------------------------- check

function check(config, usingExample) {
  const problems = [];
  const g = (k) => text(get(config, k));
  if (usingExample) {
    problems.push('config/application.yml does not exist: copy config/application.example.yml to config/application.yml and fill it in');
  }
  if (g('jwt.secret').length < 32) {
    problems.push('jwt.secret must be at least 32 characters');
  }
  for (const db of ['trading', 'auth']) {
    if (g(`database.${db}.password`) === '') {
      problems.push(`database.${db}.password is empty`);
    }
  }
  for (const [name, mode] of [
    ['auth.email', g('auth.email.mode')],
    ['order.email', g('order.email.mode')],
  ]) {
    if (!['off', 'dev', 'prod'].includes(mode)) {
      problems.push(`${name}.mode must be off, dev or prod`);
    }
    if (mode === 'prod') {
      const smtp = name === 'auth.email' ? ['host', 'user', 'password'] : ['host', 'username', 'password'];
      for (const key of smtp) {
        if (g(`${name}.smtp.${key}`) === '') {
          problems.push(`${name}.smtp.${key} is required when ${name}.mode is prod`);
        }
      }
      if (g(`${name}.from`) === '' || g(`${name}.from-domains`) === '') {
        problems.push(`${name}.from and ${name}.from-domains are required when ${name}.mode is prod`);
      }
    }
  }
  const enc = g('encryption.mode');
  if (!['off', 'optional', 'required'].includes(enc)) {
    problems.push('encryption.mode must be off, optional or required');
  } else if (enc !== 'off' && (g('encryption.private-key-pem') === '' || g('encryption.kid') === '')) {
    problems.push('encryption.kid and encryption.private-key-pem are required when encryption.mode is not off (node config/cli.js enc-key)');
  }
  return problems;
}

// ------------------------------------------------------------------------------------------------------------ main

function main() {
  const [command, arg] = process.argv.slice(2);
  if (command === 'enc-key') {
    const { generateKeyPairSync } = require('crypto');
    const { privateKey } = generateKeyPairSync('rsa', { modulusLength: 3072 });
    const pem = privateKey.export({ type: 'pkcs8', format: 'pem' }).toString().trim().replace(/\n/g, '\\n');
    console.log(`  kid: auth-${new Date().toISOString().slice(0, 7)}`);
    console.log(`  private-key-pem: "${pem}"`);
    console.error('\nPaste these two lines under `encryption:` in config/application.yml. Keep the private key out of git.');
    return;
  }
  const { config, usingExample } = load();
  switch (command) {
    case 'get': {
      const m = /^services\.([a-z]+)\.url$/.exec(arg || '');
      const value = m ? service(config, m[1]).url : get(config, arg || '');
      if (value === undefined) {
        console.error(`config: no key "${arg}"`);
        process.exit(1);
      }
      console.log(typeof value === 'object' ? JSON.stringify(value) : String(value));
      break;
    }
    case 'frontend':
      frontend(config);
      break;
    case 'serve':
      serve(config);
      break;
    case 'contracts':
      contracts(config);
      break;
    case 'compose-env': {
      const file = arg ? path.resolve(arg) : path.join(ROOT, 'services/.env');
      const lines = Object.entries(composeVariables(config)).map(([k, v]) => `${k}=${quote(v)}`);
      fs.writeFileSync(
        file,
        '# Generated by config/cli.js compose-env from config/application.yml. Do not edit; it is git-ignored.\n' + lines.join('\n') + '\n',
      );
      break;
    }
    case 'env': {
      const flat = flatten(config, '', {});
      for (const [k, v] of Object.entries(flat)) {
        console.log(`${k.toUpperCase().replace(/[.-]/g, '_')}=${quote(v)}`);
      }
      break;
    }
    case 'check': {
      const problems = check(config, usingExample);
      if (problems.length) {
        console.error('config: ' + problems.join('\nconfig: '));
        process.exit(1);
      }
      console.log('config: ok');
      break;
    }
    default:
      console.error('usage: node config/cli.js get|frontend|serve|contracts|compose-env|env|check|enc-key');
      process.exit(2);
  }
}

main();
