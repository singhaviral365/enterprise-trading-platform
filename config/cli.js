#!/usr/bin/env node
/*
 * The command line of the central configuration (config/application.yml, falling back to config/application.example.yml).
 *
 *   node config/cli.js get <dotted.key>      print one value (a service also has a derived `.url`, for example services.order.url)
 *   node config/cli.js frontend              write frontend/src/app/config/platform.config.ts and frontend/proxy.conf.json
 *   node config/cli.js serve                 the above, then `ng serve` on services.frontend.port with the proxy
 *   node config/cli.js contracts             write the `servers:` URLs of every contract in contracts/*.yaml
 *   node config/cli.js env-file              write the root .env (real values) and .env.example (the committed template) from the config
 *   node config/cli.js env                   print every key as KEY=VALUE shell lines (for shell scripts)
 *   node config/cli.js check                 explain what is missing or unsafe, exit 1 on a problem
 *   node config/cli.js enc-key               print a new payload-encryption key as the two lines to paste into application.yml
 */
'use strict';

const fs = require('fs');
const path = require('path');
const { spawn } = require('child_process');

const ROOT = path.resolve(__dirname, '..');
const REAL = process.env.CONFIG_FILE ? path.resolve(process.env.CONFIG_FILE) : path.join(__dirname, 'application.yml');
const EXAMPLE = path.join(__dirname, 'application.example.yml');

function yamlParser() {
  try {
    return require('js-yaml');
  } catch {
    console.error('config: js-yaml is missing. Run `npm install` in the config folder.');
    process.exit(2);
  }
}

function merge(base, over) {
  if (over === null || typeof over !== 'object' || Array.isArray(over)) {
    return over === undefined ? base : over;
  }
  const out = { ...(base && typeof base === 'object' && !Array.isArray(base) ? base : {}) };
  for (const [key, value] of Object.entries(over)) {
    out[key] = merge(out[key], value);
  }
  return out;
}

function load() {
  const yaml = yamlParser();
  const example = yaml.load(fs.readFileSync(EXAMPLE, 'utf8')) || {};
  const real = fs.existsSync(REAL) ? yaml.load(fs.readFileSync(REAL, 'utf8')) || {} : null;
  return { config: real ? merge(example, real) : example, usingExample: real === null };
}

function get(config, dotted) {
  return dotted.split('.').reduce((node, key) => (node === undefined || node === null ? undefined : node[key]), config);
}

function service(config, name) {
  const s = config.services[name];
  return { ...s, url: `http://${s.host}:${s.port}` };
}

function text(value) {
  return value === undefined || value === null ? '' : String(value);
}

// ---------------------------------------------------------------------------------------------------------- frontend

function writeIfChanged(file, content) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== content) {
    fs.writeFileSync(file, content);
    return true;
  }
  return false;
}

function frontend(config) {
  const urls = {
    frontendUrl: service(config, 'frontend').url,
    // PUBLIC_AUTH_URL: the address the BROWSER uses for the auth-service when it differs from services.auth (a container build)
    authUrl: process.env.PUBLIC_AUTH_URL || service(config, 'auth').url,
    orderUrl: service(config, 'order').url,
    executorUrl: service(config, 'executor').url,
    mailhogWebUrl: `http://${config.services.mailhog.host}:${config.services.mailhog['web-port']}`,
  };
  const ts =
    '// Generated by config/cli.js from config/application.yml. Do not edit; it is git-ignored and rewritten by npm start, build and test.\n' +
    'export const PLATFORM = {\n' +
    Object.entries(urls)
      .map(([k, v]) => `  ${k}: '${v}',`)
      .join('\n') +
    '\n} as const;\n';
  writeIfChanged(path.join(ROOT, 'frontend/src/app/config/platform.config.ts'), ts);

  // ng serve proxies same-origin calls to the services that have no CORS: market data to the executor, the rest of /api to the order-service.
  const proxy = {
    '/api/v1/market': { target: urls.executorUrl, secure: false, changeOrigin: true },
    '/api': { target: urls.orderUrl, secure: false, changeOrigin: true },
  };
  writeIfChanged(path.join(ROOT, 'frontend/proxy.conf.json'), JSON.stringify(proxy, null, 2) + '\n');

  // The Playwright journeys read these as E2E_* variables (frontend/playwright.config.ts); an E2E_* already in the environment wins.
  const e2e = {
    E2E_BASE_URL: urls.frontendUrl,
    E2E_MAILHOG_URL: urls.mailhogWebUrl,
    E2E_USERNAME: text(get(config, 'e2e.username')),
    E2E_PASSWORD: text(get(config, 'e2e.password')),
    E2E_READONLY_USERNAME: text(get(config, 'e2e.readonly-username')),
    E2E_READONLY_PASSWORD: text(get(config, 'e2e.readonly-password')),
    E2E_SYMBOL: text(get(config, 'e2e.symbol')),
  };
  writeIfChanged(path.join(ROOT, 'frontend/e2e/support/e2e-config.generated.json'), JSON.stringify(e2e, null, 2) + '\n');
}

function serve(config) {
  frontend(config);
  const port = String(service(config, 'frontend').port);
  const child = spawn('npx', ['ng', 'serve', '--port', port, '--proxy-config', 'proxy.conf.json', ...process.argv.slice(3)], {
    cwd: path.join(ROOT, 'frontend'),
    stdio: 'inherit',
    shell: true,
  });
  child.on('exit', (code) => process.exit(code === null ? 1 : code));
}

// --------------------------------------------------------------------------------------------------------- contracts

const AUTH_CONTRACTS = ['auth-api.yaml'];

function contracts(config) {
  const dir = path.join(ROOT, 'contracts');
  for (const file of fs.readdirSync(dir).filter((f) => f.endsWith('.yaml'))) {
    const owner = AUTH_CONTRACTS.includes(file) ? 'auth' : 'order';
    const p = path.join(dir, file);
    const raw = fs.readFileSync(p, 'utf8');
    const crlf = raw.includes('\r\n');
    const lines = raw.replace(/\r\n/g, '\n').split('\n');
    const start = lines.findIndex((l) => l === 'servers:');
    if (start < 0) {
      continue;
    }
    let first = true;
    for (let i = start + 1; i < lines.length && (lines[i].startsWith('  ') || lines[i] === ''); i++) {
      if (/^  - url: /.test(lines[i])) {
        // The first server is the one a developer runs; a later one names the service inside the docker network and is left alone.
        if (first) {
          lines[i] = `  - url: ${service(config, owner).url}`;
          first = false;
        }
      }
    }
    const out = lines.join('\n');
    fs.writeFileSync(p, crlf ? out.replace(/\n/g, '\r\n') : out);
  }
}

