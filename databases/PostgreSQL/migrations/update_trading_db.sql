-- 6. Portfolio performance (portfolio-performance-schema.sql)
-- ============================================================================

-- Portfolio performance tables (end-of-day statements and the NAV curve). Loaded after portfolio-schema.sql (see
-- spring.sql.init.schema-locations). Safe to run on every start: every statement is idempotent. The same statements are part of
-- databases/PostgreSQL/migrations/create_schema.sql (a new database) and update_trading_db.sql (an existing one).
--
-- Live figures (market value, unrealised and day P&L as at now) are NOT stored: they are computed from the current quote on every
-- request. What is stored here is the history of CLOSED days: a daily close per symbol (a cache of what Fauxnance published),
-- and one statement per account per closed day, written once and not changed (except the last few days, which are recomputed when
-- a synthetic candle is later replaced by a real one).

-- Fauxnance daily candles, shared by every account: one row per symbol per trading day. close is the price as traded (what holdings
-- are valued with: share counts are never restated); adjclose is restated for splits and dividends (what benchmark returns use).
-- Symbols are Fauxnance symbols, upper case: AAPL, INFY.NS, SPY, and FX pairs such as FX:EURUSD.
CREATE TABLE IF NOT EXISTS price_candle_daily (
    symbol VARCHAR(32) NOT NULL,
    candle_date DATE NOT NULL,
    close NUMERIC(19, 6) NOT NULL,
    adjclose NUMERIC(19, 6) NOT NULL,
    currency CHAR(3),
    -- Fauxnance generated this row to bridge an upstream gap: the day is shown as estimated.
    synthetic BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (symbol, candle_date),
    CONSTRAINT chk_price_candle_close CHECK (close > 0),
    CONSTRAINT chk_price_candle_adjclose CHECK (adjclose > 0)
);

-- The statement of one CLOSED day for one account, in the account currency.
CREATE TABLE IF NOT EXISTS portfolio_nav_daily (
    account_id INTEGER NOT NULL,
    nav_date DATE NOT NULL,
    cash NUMERIC(19, 4) NOT NULL,
    holdings_value NUMERIC(19, 4) NOT NULL,
    -- V(d) = cash + holdings_value
    total_value NUMERIC(19, 4) NOT NULL,
    -- What the holdings cost (quantity * average cost), so unrealised_pnl = holdings_value - cost_basis.
    cost_basis NUMERIC(19, 4) NOT NULL,
    unrealised_pnl NUMERIC(19, 4) NOT NULL,
    -- Realised profit and loss booked on or before this day (from the ledger).
    realised_pnl_cumulative NUMERIC(19, 4) NOT NULL,
    -- External money (or securities) put in or taken out that day. On the first day it is the whole starting value.
    net_flow NUMERIC(19, 4) NOT NULL,
    -- V(d) - V(d-1) - F(d): trades swap cash for shares and cancel, so only prices move it.
    day_pnl NUMERIC(19, 4) NOT NULL,
    units NUMERIC(24, 8) NOT NULL,
    nav NUMERIC(19, 6) NOT NULL,
    -- Any price used that day was synthetic, missing, forward-filled over a gap, or an exchange rate was today's.
    estimated BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (account_id, nav_date),
    CONSTRAINT fk_portfolio_nav_account
        FOREIGN KEY (account_id)
        REFERENCES account(account_id)
        ON DELETE CASCADE,
    CONSTRAINT chk_portfolio_nav_positive CHECK (nav > 0 AND units >= 0)
);

-- ============================================================================
-- 7. Automated strategies (strategy-schema.sql)
-- ============================================================================

-- Automated Strategy Execution (ASE) tables. Loaded after schema.sql (see spring.sql.init.schema-locations).
-- Safe to run on every start: every statement is idempotent. See documentation/readme/STRATEGIES.md.
--
-- A strategy is a rule a customer sets once: "buy 50 of AAPL when the price falls below 150". The order-service owns the
-- table (create, list, disable, cancel). The executor-service reads it on every market-data quote and, when the rule is
-- met, claims it and places the order through POST /api/v1/orders. Both services share this table, so the status values
-- and the transitions between them are enforced HERE, once, and not left to either service to get right.
--
-- Status
--   ACTIVE     armed: the executor may act on it.
--   EXECUTING  claimed by the executor for one run. Only the executor sets this, and only from ACTIVE.
--   DISABLED   switched off by the customer; can be switched back on. Never acted on.
--   EXECUTED   ran as many times as it was allowed to. Final.
--   CANCELLED  withdrawn by the customer. Final.
--   EXPIRED    its end date passed before it finished. Final.
--   FAILED     stopped by the platform after max_failures failures in a row. Final.

CREATE TABLE IF NOT EXISTS strategy (
    strategy_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    account_id INTEGER NOT NULL,
    instrument_id INTEGER NOT NULL,
    side VARCHAR(4) NOT NULL,
    quantity BIGINT NOT NULL,
    -- BELOW fires when the price is at or under trigger_price, ABOVE when it is at or over. In the instrument's currency.
    trigger_direction VARCHAR(5) NOT NULL,
    trigger_price NUMERIC(19, 4) NOT NULL,
    -- "Falls through a level" means the price moves through it. A strategy is created un-armed unless the price was seen
    -- on the safe side of the level, and the executor arms it on the first quote that is. It never fires while un-armed,
    -- so a rule set when the price is already past its level waits for a real crossing instead of trading at once.
    armed BOOLEAN NOT NULL DEFAULT FALSE,
    -- The optional time window. NULL means no limit on that side.
    valid_from TIMESTAMPTZ,
    valid_until TIMESTAMPTZ,
    -- The damage limits. Checked by the executor at the point of decision, before every order.
    max_order_value NUMERIC(19, 2) NOT NULL,
    max_position_qty BIGINT NOT NULL,
    max_executions INTEGER NOT NULL DEFAULT 1,
    max_failures INTEGER NOT NULL DEFAULT 3,
    executions INTEGER NOT NULL DEFAULT 0,
    consecutive_failures INTEGER NOT NULL DEFAULT 0,
    status VARCHAR(10) NOT NULL DEFAULT 'ACTIVE',
    status_reason VARCHAR(200),
    last_order_id BIGINT,
    -- When the executor claimed it (a crash while EXECUTING is recovered from this).
    claimed_at TIMESTAMPTZ,
    -- The last status the customer was told about (FAILED or EXPIRED), so each is announced once.
    notified_status VARCHAR(10),
    version BIGINT NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    executed_at TIMESTAMPTZ,
    cancelled_at TIMESTAMPTZ,
    CONSTRAINT pk_strategy PRIMARY KEY (strategy_id),
    CONSTRAINT fk_strategy_account
        FOREIGN KEY (account_id)
        REFERENCES account(account_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_strategy_instrument
        FOREIGN KEY (instrument_id)
        REFERENCES instrument(instrument_id)
        ON DELETE RESTRICT,
    CONSTRAINT chk_strategy_side CHECK (side IN ('BUY', 'SELL')),
    CONSTRAINT chk_strategy_quantity CHECK (quantity > 0),
    CONSTRAINT chk_strategy_direction CHECK (trigger_direction IN ('BELOW', 'ABOVE')),
    CONSTRAINT chk_strategy_trigger_price CHECK (trigger_price > 0),
    CONSTRAINT chk_strategy_window CHECK (valid_from IS NULL OR valid_until IS NULL OR valid_until > valid_from),
    CONSTRAINT chk_strategy_max_order_value CHECK (max_order_value > 0),
    CONSTRAINT chk_strategy_max_position CHECK (max_position_qty > 0),
    CONSTRAINT chk_strategy_max_executions CHECK (max_executions BETWEEN 1 AND 20),
    CONSTRAINT chk_strategy_max_failures CHECK (max_failures BETWEEN 1 AND 10),
    CONSTRAINT chk_strategy_executions CHECK (executions >= 0 AND consecutive_failures >= 0),
    CONSTRAINT chk_strategy_status CHECK (
        status IN ('ACTIVE', 'EXECUTING', 'DISABLED', 'EXECUTED', 'CANCELLED', 'EXPIRED', 'FAILED'))
);

-- The executor's per-quote lookup: ACTIVE strategies on one instrument. A partial index, so it stays small however many
-- finished strategies pile up.
CREATE INDEX IF NOT EXISTS idx_strategy_active_instrument
    ON strategy(instrument_id)
    WHERE status = 'ACTIVE';

-- The customer's list, newest first.
CREATE INDEX IF NOT EXISTS idx_strategy_account
    ON strategy(account_id, created_at DESC);

-- What the sweepers look for: claims that never finished, and finished strategies not yet announced.
CREATE INDEX IF NOT EXISTS idx_strategy_executing
    ON strategy(claimed_at)
    WHERE status = 'EXECUTING';

-- ---------------------------------------------------------------------------------------------------------------------
-- Lifecycle rules. A final status can never be left, and the executor can only claim an ACTIVE strategy.
-- ---------------------------------------------------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION enforce_strategy_lifecycle()
RETURNS TRIGGER
LANGUAGE plpgsql
AS '
BEGIN
    IF OLD.status IN (''EXECUTED'', ''CANCELLED'', ''EXPIRED'', ''FAILED'')
       AND NEW.status <> OLD.status THEN
        RAISE EXCEPTION ''A % strategy cannot change status'', OLD.status;
    END IF;

    IF NEW.status = ''EXECUTING'' AND OLD.status <> ''ACTIVE'' AND OLD.status <> ''EXECUTING'' THEN
        RAISE EXCEPTION ''Only an ACTIVE strategy can be claimed. Current status: %'', OLD.status;
    END IF;

    IF NEW.status = ''CANCELLED'' AND NEW.cancelled_at IS NULL THEN
        NEW.cancelled_at := CURRENT_TIMESTAMP;
    END IF;

    IF NEW.status = ''EXECUTED'' AND NEW.executed_at IS NULL THEN
        NEW.executed_at := CURRENT_TIMESTAMP;
    END IF;

    NEW.updated_at := CURRENT_TIMESTAMP;
    RETURN NEW;
END;
';

DROP TRIGGER IF EXISTS trg_strategy_lifecycle ON strategy;

CREATE TRIGGER trg_strategy_lifecycle
BEFORE UPDATE ON strategy
FOR EACH ROW
EXECUTE FUNCTION enforce_strategy_lifecycle();

-- ---------------------------------------------------------------------------------------------------------------------
-- The audit trail: one row per attempt to run a strategy, whatever came of it. This is what answers "why did it (not)
-- trade?" and what the live demonstration of disabling a strategy mid-cycle is shown from.
--
-- run_number names the order the attempt is for. The idempotency key of that order is strat-{strategy_id}-{run_number},
-- and it stays the same across retries of the same run, so a retry after a timeout cannot place a second order.
-- ---------------------------------------------------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS strategy_run (
    run_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    strategy_id BIGINT NOT NULL,
    run_number INTEGER NOT NULL,
    quote_price NUMERIC(19, 4),
    quote_at TIMESTAMPTZ,
    outcome VARCHAR(14) NOT NULL,
    order_id BIGINT,
    detail VARCHAR(200),
    -- How the order ended (FILLED, REJECTED, CANCELLED), filled in when its trade event arrives.
    settled_status VARCHAR(10),
    settled_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_strategy_run PRIMARY KEY (run_id),
    CONSTRAINT fk_strategy_run_strategy
        FOREIGN KEY (strategy_id)
        REFERENCES strategy(strategy_id)
        ON DELETE CASCADE,
    CONSTRAINT chk_strategy_run_outcome CHECK (
        outcome IN ('ORDERED', 'DUPLICATE', 'BLOCKED_LIMIT', 'REJECTED', 'API_ERROR', 'STALE', 'DISABLED')),
    CONSTRAINT chk_strategy_run_settled CHECK (
        settled_status IS NULL OR settled_status IN ('FILLED', 'REJECTED', 'CANCELLED')),
    CONSTRAINT chk_strategy_run_number CHECK (run_number >= 1)
);

-- At most one order per run, however many times the same trigger is delivered.
CREATE UNIQUE INDEX IF NOT EXISTS uq_strategy_run_order
    ON strategy_run(strategy_id, run_number)
    WHERE outcome IN ('ORDERED', 'DUPLICATE');

CREATE INDEX IF NOT EXISTS idx_strategy_run_strategy
    ON strategy_run(strategy_id, run_id DESC);

-- How an order is traced back to its run when its trade event arrives.
CREATE INDEX IF NOT EXISTS idx_strategy_run_order
    ON strategy_run(order_id)
    WHERE order_id IS NOT NULL;

